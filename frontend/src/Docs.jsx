import { useRef, useState } from "react";

const BASES = ["Fort Myers", "Naples", "Cape Coral", "Sanibel & Captiva", "Fort Myers Beach", "Bonita Springs / Estero", "Punta Gorda", "Marco Island"];
const INTERESTS = ["🏖️ Beaches", "🐊 Nature & wildlife", "🍤 Food", "🏛️ History & culture", "👨‍👩‍👧 Family / kids", "🛶 Kayaking & boating", "🛍️ Shopping", "🌙 Nightlife", "💸 Budget-friendly"];

/** Inline form for "Plan an itinerary" / "Make a guide". Calls onSubmit(label, task). */
export function DocBuilder({ mode, onClose, onSubmit, disabled }) {
  const [days, setDays] = useState(2);
  const [base, setBase] = useState(BASES[0]);
  const [interests, setInterests] = useState([]);
  const [notes, setNotes] = useState("");
  const [topic, setTopic] = useState("");

  const toggle = (i) => setInterests((xs) => (xs.includes(i) ? xs.filter((x) => x !== i) : [...xs, i]));
  const clean = (i) => i.replace(/^\S+\s/, "");

  function submit(e) {
    e.preventDefault();
    if (mode === "itinerary") {
      const picked = interests.map(clean);
      const label = `🗺️ Plan a ${days}-day itinerary based in ${base}${picked.length ? ` — ${picked.join(", ")}` : ""}${notes ? ` (${notes})` : ""}`;
      onSubmit(label, { kind: "itinerary", days, base, interests: picked, notes });
    } else {
      const label = `📄 Make me a guide${topic ? `: ${topic}` : " from our conversation"}`;
      onSubmit(label, { kind: "guide", topic });
    }
  }

  return (
    <form className="builder" onSubmit={submit}>
      <div className="builder-head">
        <strong>{mode === "itinerary" ? "🗺️ Plan an itinerary" : "📄 Make a guide"}</strong>
        <button type="button" className="ghost small" onClick={onClose}>✕</button>
      </div>
      {mode === "itinerary" ? (
        <>
          <div className="row">
            <label>
              Days
              <select value={days} onChange={(e) => setDays(+e.target.value)}>
                {[1, 2, 3, 4, 5, 6, 7].map((d) => <option key={d} value={d}>{d}</option>)}
              </select>
            </label>
            <label className="grow">
              Home base
              <select value={base} onChange={(e) => setBase(e.target.value)}>
                {BASES.map((b) => <option key={b}>{b}</option>)}
              </select>
            </label>
          </div>
          <div className="chips">
            {INTERESTS.map((i) => (
              <button type="button" key={i} className={interests.includes(i) ? "chip small active" : "chip small"} onClick={() => toggle(i)}>
                {i}
              </button>
            ))}
          </div>
          <input value={notes} onChange={(e) => setNotes(e.target.value)} placeholder="Anything else? (e.g. visiting in March, no car, traveling with a dog)" />
        </>
      ) : (
        <input value={topic} onChange={(e) => setTopic(e.target.value)} placeholder="Topic (leave blank to turn this conversation into a guide) — e.g. hurricane prep for renters" />
      )}
      <button type="submit" disabled={disabled}>{mode === "itinerary" ? "Build my itinerary" : "Write my guide"}</button>
    </form>
  );
}

function titleOf(markdown) {
  const m = markdown.match(/^#\s+(.+)$/m);
  return (m ? m[1] : "SWFL Compass guide").replace(/[*_`]/g, "").trim();
}

/** A generated document: rendered markdown plus download / print / copy. */
export function DocumentCard({ content, children }) {
  const ref = useRef(null);
  const [copied, setCopied] = useState(false);
  const title = titleOf(content);
  const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "guide";

  function download() {
    const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
    const a = Object.assign(document.createElement("a"), { href: URL.createObjectURL(blob), download: `${slug}.md` });
    a.click();
    URL.revokeObjectURL(a.href);
  }

  function print() {
    const w = window.open("", "_blank");
    if (!w) return;
    w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${title}</title>
<style>
body{font-family:"Segoe UI",system-ui,sans-serif;max-width:760px;margin:32px auto;padding:0 24px;color:#12302c;line-height:1.55}
h1{color:#00885a;border-bottom:3px solid #00885a;padding-bottom:6px}h2{color:#0b5ea8;margin-top:28px}
a{color:#0b5ea8}li{margin:3px 0}.foot{margin-top:40px;font-size:12px;color:#5d7570;border-top:1px solid #ddd;padding-top:8px}
</style></head><body>${ref.current.innerHTML}
<div class="foot">Generated by SWFL Compass · ${new Date().toLocaleDateString()} · Verify hours, prices and safety info with official sources.</div>
</body></html>`);
    w.document.close();
    w.focus();
    setTimeout(() => w.print(), 300);
  }

  async function copy() {
    await navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  }

  return (
    <div className="doc">
      <div className="doc-bar">
        <span className="doc-badge">📄 Document</span>
        <div className="doc-actions">
          <button onClick={download}>⬇ Download .md</button>
          <button onClick={print}>🖨 Print / Save PDF</button>
          <button className="ghost" onClick={copy}>{copied ? "Copied!" : "📋 Copy"}</button>
        </div>
      </div>
      <div className="doc-body answer" ref={ref}>{children}</div>
    </div>
  );
}
